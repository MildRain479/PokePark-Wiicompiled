const char* tr(const char* english) {
    int i, lang = g_language_started;
    if (!english || lang <= LANGUAGE_EN || lang >= LANGUAGES) return english;
    for (i = 0; i < (int)(sizeof(kText) / sizeof(kText[0])); i++) {
        if (!strcmp(kText[i][0], english)) return kText[i][lang];
    }
    return english;
}
