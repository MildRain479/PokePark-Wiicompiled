# Android: libpokepark.so for arm64 with the NDK's clang, in an APK put
# together with the SDK's aapt2, d8, zipalign and apksigner (no Gradle; the
# app is a NativeActivity with one small Java class, which asks for the disc
# image; recomp/android/AndroidManifest.xml). The disc image is read with
# nod (https://github.com/encounter/nod), built here with cargo for arm64.

ANDROID_API = 30


def android_sdk():
    sdk = os.environ.get("ANDROID_HOME") or os.environ.get("ANDROID_SDK_ROOT") or \
        os.path.join(os.environ.get("LOCALAPPDATA", ""), "Android", "Sdk")
    if not os.path.isdir(sdk):
        sys.exit("android: no Android SDK (set ANDROID_HOME)")
    return sdk


def newest(paths):
    return sorted(paths, key=lambda d: [int(x) for x in os.path.basename(d).split(".") if x.isdigit()])[-1] \
        if paths else None


def android_ndk(sdk):
    ndk = os.environ.get("ANDROID_NDK_HOME") or newest(glob.glob(os.path.join(sdk, "ndk", "*")))
    if not ndk or not os.path.isdir(ndk):
        sys.exit("android: no NDK (install NDK (Side by side) in the SDK manager, or set ANDROID_NDK_HOME)")
    return ndk


# Java, for apksigner: on the PATH, JAVA_HOME, or Android Studio's own.
def java_env():
    env = dict(os.environ)
    if not shutil.which("java"):
        home = env.get("JAVA_HOME") or next((d for d in (r"C:\Program Files\Android\Android Studio\jbr",
                                                         "/Applications/Android Studio.app/Contents/jbr/Contents/Home",
                                                         "/opt/android-studio/jbr") if os.path.isdir(d)), None)
        if home:
            env["JAVA_HOME"] = home
            env["PATH"] = os.path.join(home, "bin") + os.pathsep + env.get("PATH", "")
    return env


NOD_COMMIT = "ebd80cac99b48a323200d84365e07a58cc27412d"  # nod 2.0.0-alpha.12
NOD_FEATURES = "compress-bzip2-vendored,compress-lzma-vendored,compress-zlib-vendored,compress-zstd-vendored,threading"


def android_nod(clang_dir):
    """nod's C library (nod-ffi) for arm64 Android: libnod.a and its include
    folder, fetched at NOD_COMMIT into build/recomp/nod and built with cargo
    (and the Rust target aarch64-linux-android) once."""
    src = os.path.join(OUT, "nod")
    lib = os.path.join(src, "target", "aarch64-linux-android", "release", "libnod.a")
    if not os.path.isdir(os.path.join(src, ".git")):
        subprocess.check_call(["git", "clone", "https://github.com/encounter/nod.git", src])
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=src, capture_output=True, text=True).stdout.strip()
    if head != NOD_COMMIT:
        subprocess.check_call(["git", "fetch", "origin"], cwd=src)
        subprocess.check_call(["git", "checkout", "-q", NOD_COMMIT], cwd=src)
    if head != NOD_COMMIT or not os.path.exists(lib):
        cc = os.path.join(clang_dir, f"aarch64-linux-android{ANDROID_API}-clang" + (".cmd" if os.name == "nt" else ""))
        env = dict(os.environ, CC_aarch64_linux_android=cc, CARGO_TARGET_AARCH64_LINUX_ANDROID_LINKER=cc,
                   AR_aarch64_linux_android=os.path.join(clang_dir, "llvm-ar" + (".exe" if os.name == "nt" else "")))
        subprocess.check_call(["rustup", "target", "add", "aarch64-linux-android"])
        subprocess.check_call(["cargo", "build", "--release", "-p", "nod-ffi", "--target", "aarch64-linux-android",
                               "--no-default-features", "--features", NOD_FEATURES], cwd=src, env=env)
    return lib, os.path.join(src, "nod-ffi", "include")


def build_android(common, boot, install, public):
    import concurrent.futures
    import zipfile
    sdk = android_sdk()
    ndk = android_ndk(sdk)
    host = "windows-x86_64" if os.name == "nt" else ("darwin-x86_64" if sys.platform == "darwin" else "linux-x86_64")
    exe = ".exe" if os.name == "nt" else ""
    clang = os.path.join(ndk, "toolchains", "llvm", "prebuilt", host, "bin", "clang" + exe)
    glue = os.path.join(ndk, "sources", "android", "native_app_glue")
    tools = newest(glob.glob(os.path.join(sdk, "build-tools", "*")))
    platform = newest([p for p in glob.glob(os.path.join(sdk, "platforms", "android-*"))
                       if os.path.exists(os.path.join(p, "android.jar"))])
    if not tools or not platform:
        sys.exit("android: the SDK has no build tools or platform")
    vulkan_shaders(os.path.join(ndk, "shader-tools", host, "glslc" + exe))
    nod_lib, nod_inc = android_nod(os.path.dirname(clang))
    out = os.path.join(OUT, "android")
    objdir = os.path.join(out, "obj")
    os.makedirs(objdir, exist_ok=True)
    srcs = common + [s for s in boot if not s.endswith("_win32.c") and not s.endswith("gl_backend.c")]
    srcs.append(os.path.join(glue, "android_native_app_glue.c"))
    inc = ["-I" + os.path.join(ROOT, "recomp", d) for d in ("runtime", "gpu")] + \
          ["-I" + GEN, "-I" + os.path.join(ROOT, "src"), "-I" + glue, "-I" + nod_inc]
    defs = [f"-D{d}" for d in DEFINES if d != "RECOMP_DEBUG_MENU"] + ["-DRECOMP_VULKAN"]
    flags = [f"--target=aarch64-linux-android{ANDROID_API}", "-O2", "-fPIC", "-std=gnu11", "-w", "-g"] + inc + defs
    shaders = os.path.join(GEN, "vk_shaders.h")

    def obj_of(s):
        return os.path.join(objdir, os.path.basename(s) + ".o")

    def needs(s):
        o = obj_of(s)
        return stale(s, o) or (s.endswith("vk_backend.c") and os.path.getmtime(shaders) > os.path.getmtime(o))

    todo = [s for s in srcs if needs(s)]
    print(f"android: compiling {len(todo)} of {len(srcs)} files")

    def compile_(s):
        r = subprocess.run([clang] + flags + ["-c", s, "-o", obj_of(s)], capture_output=True, text=True)
        return s, r

    failed = False
    with concurrent.futures.ThreadPoolExecutor(os.cpu_count() or 4) as pool:
        for s, r in pool.map(compile_, todo):
            if r.returncode:
                failed = True
                print(f"android: {os.path.basename(s)} failed:\n{r.stderr}")
    if failed:
        sys.exit(1)
    lib = os.path.join(out, "lib", "arm64-v8a", "libpokepark.so")
    os.makedirs(os.path.dirname(lib), exist_ok=True)
    # native_app_glue's entry point is only referred to by the activity,
    # by name. 16 KB pages, as newer phones have.
    subprocess.check_call([clang, f"--target=aarch64-linux-android{ANDROID_API}", "-shared", "-o", lib,
                           "-u", "ANativeActivity_onCreate", "-Wl,-z,max-page-size=16384"] +
                          [obj_of(s) for s in srcs] + [nod_lib, "-landroid", "-llog", "-laaudio", "-ljnigraphics",
                                                       "-lz", "-ldl", "-lm"])  # zlib: nod's
    # The activity's Java (PokeParkActivity.java), as classes.dex.
    java_src = sorted(glob.glob(os.path.join(ROOT, "recomp", "android", "java", "**", "*.java"), recursive=True))
    classes = os.path.join(out, "classes")
    shutil.rmtree(classes, ignore_errors=True)
    os.makedirs(classes)
    jenv = java_env()
    javac = shutil.which("javac", path=jenv["PATH"]) or "javac"
    subprocess.check_call([javac, "--release", "8", "-nowarn", "-classpath", os.path.join(platform, "android.jar"),
                           "-d", classes] + java_src, env=jenv)
    subprocess.check_call([os.path.join(tools, "d8.bat" if os.name == "nt" else "d8"), "--release", "--min-api",
                           str(ANDROID_API), "--lib", os.path.join(platform, "android.jar"), "--output", out] +
                          glob.glob(os.path.join(classes, "**", "*.class"), recursive=True), env=jenv)
    # The APK: the manifest, its resources (the launcher icon) and the
    # prompt icons (as assets), then the library, uncompressed and
    # page-aligned so it is loaded in place.
    res = os.path.join(out, "res.zip")
    subprocess.check_call([os.path.join(tools, "aapt2" + exe), "compile", "--dir",
                           os.path.join(ROOT, "recomp", "android", "res"), "-o", res])
    assets = os.path.join(out, "assets")
    shutil.rmtree(assets, ignore_errors=True)
    shutil.copytree(os.path.join(ROOT, "recomp", "assets", "prompts"), os.path.join(assets, "prompts"),
                    ignore=shutil.ignore_patterns("*.md"))
    os.makedirs(os.path.join(assets, "licenses"))
    shutil.copy2(os.path.join(ROOT, "recomp", "assets", "nod_license.txt"), os.path.join(assets, "licenses"))
    base = os.path.join(out, "base.apk")
    subprocess.check_call([os.path.join(tools, "aapt2" + exe), "link", "-o", base,
                           "--manifest", os.path.join(ROOT, "recomp", "android", "AndroidManifest.xml"),
                           "-I", os.path.join(platform, "android.jar"), "-A", assets, res] +
                          ([] if public else ["--debug-mode"]))  # debuggable: run-as, stack dumps
    # Stripped in the APK; the library with its symbols stays in lib/, for
    # reading crash backtraces (ndk-stack).
    stripped = os.path.join(out, "libpokepark.so")
    subprocess.check_call([os.path.join(os.path.dirname(clang), "llvm-strip" + exe), "--strip-debug", "-o", stripped, lib])
    full = os.path.join(out, "full.apk")
    with zipfile.ZipFile(base) as src, zipfile.ZipFile(full, "w") as z:
        for item in src.infolist():
            z.writestr(item, src.read(item.filename), compress_type=item.compress_type)
        z.write(stripped, "lib/arm64-v8a/libpokepark.so", compress_type=zipfile.ZIP_STORED)
        z.write(os.path.join(out, "classes.dex"), "classes.dex", compress_type=zipfile.ZIP_DEFLATED)
    base = full
    aligned = os.path.join(out, "aligned.apk")
    subprocess.check_call([os.path.join(tools, "zipalign" + exe), "-f", "-P", "16", "4", base, aligned])
    # Signed with the SDK's debug key, made as Android Studio would if
    # there isn't one yet.
    keystore = os.path.join(os.path.expanduser("~"), ".android", "debug.keystore")
    if not os.path.exists(keystore):
        keytool = shutil.which("keytool", path=java_env()["PATH"]) or "keytool"
        subprocess.check_call([keytool, "-genkeypair", "-keystore", keystore, "-storepass", "android", "-alias",
                               "androiddebugkey", "-keypass", "android", "-keyalg", "RSA", "-validity", "10000",
                               "-dname", "CN=Android Debug,O=Android,C=US"])
    apk = os.path.join(out, "PokePark.apk")
    signer = os.path.join(tools, "apksigner.bat" if os.name == "nt" else "apksigner")
    subprocess.check_call([signer, "sign", "--ks", keystore, "--ks-pass", "pass:android", "--out", apk, aligned],
                          env=java_env())
    print("android:", apk)
    if install:
        adb = os.path.join(sdk, "platform-tools", "adb" + exe)
        subprocess.check_call([adb, "install", "-r", apk])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", choices=sorted(TARGETS))
    ap.add_argument("--opt", default=None, help="optimization flag (default /O2 or -O2)")
    ap.add_argument("--release", action="store_true", help="whole-program optimization (MSVC /GL with /LTCG)")
    ap.add_argument("--pgo", action="store_true",
                    help="with --release: optimize the boot program with a profile of a run through the park")
    ap.add_argument("--pgo-train", action="store_true", help="with --pgo: make a new profile")
    ap.add_argument("--no-trace", action="store_true",
                    help="without the trace of recent calls (RECOMP_TRACE) kept for crash reports and RECOMP_CALLS")
    ap.add_argument("--public", action="store_true",
                    help="release build without the debug settings menu, put together in Releases/")
    ap.add_argument("--dist", action="store_true",
                    help="copy the boot program, as PokePark.exe, and its files to build/recomp/dist")
    ap.add_argument("--android", action="store_true", help="the Android app (arm64), build/recomp/android/PokePark.apk")
    ap.add_argument("--install", action="store_true", help="with --android: install it on the phone with adb")
    ap.add_argument("args", nargs="*", help="extra arguments for --run")
    args = ap.parse_args()
    global OBJ
    if args.public:
        args.release = True
    if args.release:
        args.opt = "/O2 /GL" if os.name == "nt" else "-O2 -flto"
    # Objects built with other flags go elsewhere, so switching rebuilds.
    if args.opt and args.opt not in ("/O2", "-O2"):
        OBJ = os.path.join(OUT, "obj_" + "".join(ch for ch in args.opt if ch.isalnum()))
    if args.no_trace:
        DEFINES.remove("RECOMP_TRACE")
        OBJ += "_notrace"
    if args.public:
        DEFINES.remove("RECOMP_DEBUG_MENU")
        OBJ += "_public"

    global VULKAN
    VULKAN = None if args.android else vulkan_sdk()
    if VULKAN:
        DEFINES.append("RECOMP_VULKAN")
        vulkan_shaders(os.path.join(VULKAN, "Bin", "glslc.exe" if os.name == "nt" else "glslc"))
    elif not args.android:
        print("no Vulkan SDK: building without the Vulkan device")

    gen = sorted(glob.glob(os.path.join(GEN, "*.c")))
    if not gen:
        sys.exit("run tools/recomp/recomp.py first")
    common = gen + sorted(glob.glob(os.path.join(ROOT, "recomp", "runtime", "*.c")))
    common += sorted(glob.glob(os.path.join(ROOT, "recomp", "patches", "*.c")))
    # Headers aren't tracked; a changed header rebuilds everything.
    headers = (glob.glob(os.path.join(ROOT, "recomp", "runtime", "*.h")) + glob.glob(os.path.join(ROOT, "recomp", "gpu", "*.h")) +
               [os.path.join(GEN, "recomp_funcs.h")])
    newest = max(os.path.getmtime(h) for h in headers if os.path.exists(h))
    objs = (glob.glob(os.path.join(OUT, "android", "obj", "*.o")) if args.android else
            glob.glob(os.path.join(OBJ, "**", "*.o*"), recursive=True))
    for o in objs:
        if os.path.getmtime(o) < newest:
            os.remove(o)
    if args.android:
        # Its settings are the Options tab's alone, as in public builds.
        build_android(common, sorted(glob.glob(os.path.join(ROOT, "recomp", "boot", "*.c")) +
                                     glob.glob(os.path.join(ROOT, "recomp", "gpu", "*.c"))), args.install, args.public)
        return
    if os.name == "nt":
        build_msvc(common, TARGETS, args.opt or "/O2")
        if args.pgo and args.release:
            pgo(args.pgo_train)
    else:
        build_cc(common, TARGETS, args.opt or "-O2")
    # The button prompt icons, beside the program (prompts.c).
    shutil.copytree(os.path.join(ROOT, "recomp", "assets", "prompts"), os.path.join(OUT, "prompts"), dirs_exist_ok=True)
    if args.dist:
        # Started without arguments it finds the game in an R8AE01 folder
        # beside it or above it (boot.c), so this runs in place.
        dist = os.path.join(OUT, "dist")
        os.makedirs(dist, exist_ok=True)
        shutil.copy2(os.path.join(OUT, "boot.exe"), os.path.join(dist, "PokePark.exe"))
        shutil.copytree(os.path.join(OUT, "prompts"), os.path.join(dist, "prompts"), dirs_exist_ok=True)
        # decomp-toolkit, which the game's set-up screen extracts disc images with (import_win32.c).
        dtk = os.path.join(ROOT, "build", "tools", "dtk.exe")
        if os.path.exists(dtk):
            os.makedirs(os.path.join(dist, "tools"), exist_ok=True)
            shutil.copy2(dtk, os.path.join(dist, "tools", "dtk.exe"))
            shutil.copy2(os.path.join(ROOT, "recomp", "assets", "dtk_license.txt"), os.path.join(dist, "tools", "dtk_license.txt"))
        print("dist:", dist)
    if args.public:
        # What players download: the program, its icons, the disc reader and
        # a readme. Nothing of the game's.
        rel = os.path.join(ROOT, "Releases")
        os.makedirs(rel, exist_ok=True)
        for old in ("prompts", "tools"):
            shutil.rmtree(os.path.join(rel, old), ignore_errors=True)
        shutil.copy2(os.path.join(OUT, "boot.exe"), os.path.join(rel, "PokePark.exe"))
        shutil.copytree(os.path.join(ROOT, "recomp", "assets", "prompts"), os.path.join(rel, "prompts"))
        shutil.copy2(os.path.join(ROOT, "recomp", "assets", "release_readme.txt"), os.path.join(rel, "README.txt"))
        dtk = os.path.join(ROOT, "build", "tools", "dtk.exe")
        if os.path.exists(dtk):
            os.makedirs(os.path.join(rel, "tools"))
            shutil.copy2(dtk, os.path.join(rel, "tools", "dtk.exe"))
            shutil.copy2(os.path.join(ROOT, "recomp", "assets", "dtk_license.txt"), os.path.join(rel, "tools", "dtk_license.txt"))
        else:
            print("public: no build/tools/dtk.exe; the release can't read disc images without it")
        print("public:", rel)
    if args.run:
        exe = os.path.join(OUT, args.run + (".exe" if os.name == "nt" else ""))
        sys.exit(subprocess.call([exe, DOL] + args.args))


if __name__ == "__main__":
    main()
