def vcvars():
    vswhere = os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"),
                           "Microsoft Visual Studio", "Installer", "vswhere.exe")
    path = subprocess.check_output([vswhere, "-latest", "-products", "*", "-property", "installationPath"],
                                   text=True).strip()
    return os.path.join(path, "VC", "Auxiliary", "Build", "vcvars64.bat")


def stale(src, obj):
    return not os.path.exists(obj) or os.path.getmtime(obj) < os.path.getmtime(src)


# The Vulkan SDK (VULKAN_SDK, else the newest in C:\VulkanSDK): its headers
# and glslc, for the Vulkan device (vk_backend.c). The game loads Vulkan
# itself and needs none of it to run. Without it the device is left out.
def vulkan_sdk():
    sdk = os.environ.get("VULKAN_SDK")
    if not sdk and os.name == "nt":
        found = sorted(glob.glob(r"C:\VulkanSDK\*"), key=lambda d: [int(x) for x in os.path.basename(d).split(".")
                                                                    if x.isdigit()])
        sdk = found[-1] if found else None
    return sdk if sdk and os.path.exists(os.path.join(sdk, "Include", "vulkan", "vulkan.h")) else None


# The Vulkan shaders, compiled to SPIR-V as C arrays in gen/vk_shaders.h
# when one changed (and vk_backend.c with it).
def vulkan_shaders(glslc):
    srcs = sorted(glob.glob(os.path.join(ROOT, "recomp", "gpu", "vk_shaders", "*.*")))
    out = os.path.join(GEN, "vk_shaders.h")
    if os.path.exists(out) and all(os.path.getmtime(s) <= os.path.getmtime(out) for s in srcs):
        return
    parts = ["/* Generated by tools/recomp/build.py from recomp/gpu/vk_shaders. */\n"]
    for src in srcs:
        base = os.path.basename(src)
        name = "kSpv_" + base.replace(".", "_")
        # gx.frag unoptimized: glslc would inline its 16 specialized stages
        # into 350 KB; the driver inlines what is left after specializing.
        opt = [] if base == "gx.frag" else ["-O"]
        # gx.vert and gx.frag once for each count of texture coordinates
        # passed between them (TEX_IO), name_0 to name_8.
        builds = [(f"{name}_{n}", [f"-DTEX_IO={n}"]) for n in range(9)] if base in ("gx.vert", "gx.frag") else [(name, [])]
        for out_name, defs in builds:
            code = subprocess.check_output([glslc, "--target-env=vulkan1.3", *opt, *defs, "-mfmt=c", "-o", "-", src],
                                           text=True)
            parts.append(f"static const uint32_t {out_name}[] = {code.strip()};\n")
        if len(builds) > 1:
            parts.append(f"static const uint32_t* const {name}[] = {{{', '.join(b for b, _ in builds)}}};\n")
            parts.append(f"static const size_t {name}_size[] = {{{', '.join(f'sizeof({b})' for b, _ in builds)}}};\n")
    with open(out, "w") as f:
        f.write("".join(parts))
    for o in glob.glob(os.path.join(OBJ, "**", "vk_backend.o*"), recursive=True):
        os.remove(o)


def build_msvc(common, targets, opt):
    inc = (f'/I"{os.path.join(ROOT, "recomp", "runtime")}" /I"{GEN}" /I"{os.path.join(ROOT, "src")}" '
           f'/I"{os.path.join(ROOT, "recomp", "gpu")}"')
    if VULKAN:
        inc += f' /I"{os.path.join(VULKAN, "Include")}"'
    defs = " ".join(f"/D{d}" for d in DEFINES)
    # The generated code relies on wrapping unsigned arithmetic only.
    flags = f"/nologo {opt} /MP /W0 /fp:precise /Zi {defs} {inc}"
    bat = os.path.join(OUT, "build.bat")
    objdir = OBJ
    with open(bat, "w") as f:
        f.write(f'@call "{vcvars()}" >nul 2>nul\n')

        def compile_(srcs, odir, lang):
            os.makedirs(odir, exist_ok=True)
            todo = [s for s in srcs if stale(s, os.path.join(odir, os.path.splitext(os.path.basename(s))[0] + ".obj"))]
            if todo:
                extra = "/TC" if lang == "c" else "/TP /EHsc /std:c++17"
                f.write(f'cl {flags} {extra} /Fd"{odir}\\\\" /Fo"{odir}\\\\" /c ' +
                        " ".join(f'"{s}"' for s in todo) + " || exit /b 1\n")

        compile_(common, objdir, "c")
        for name, srcs in targets.items():
            tdir = os.path.join(objdir, name)
            compile_([s for s in srcs if s.endswith(".c")], tdir, "c")
            compile_([s for s in srcs if not s.endswith(".c")], tdir, "cpp")
            exe = os.path.join(OUT, name + ".exe")
            libs = " ".join(LIBS.get(name, []))
            ltcg = "/LTCG" if "/GL" in opt else ""
            f.write(f'link /nologo /DEBUG /PDBALTPATH:%%_PDB%% /MANIFEST:EMBED {ltcg} /OUT:"{exe}" "{objdir}\\*.obj" "{tdir}\\*.obj" {libs} || exit /b 1\n')
    subprocess.check_call(["cmd", "/c", bat])


# Profile-guided optimization (MSVC): the boot program linked instrumented,
# run through the park (the title, a save file, into the park and walking
# about) to see which code runs most, and linked again with that. The
# profile is kept in build/recomp/pgo and used by later builds (code that
# changed since goes without) until --pgo-train makes a new one.
def pgo_script():
    # Slowly: the instrumented program runs at about 15 fps.
    sc = [f"{t}:2 {t}.5:" for t in range(20, 141, 12)]
    t = 150
    for d in "up up+left up right up down+right up left up right up down up+left up right up".split():
        sc.append(f"{t}:{d}")
        t += 8
    return " ".join(sc)


def pgo(train):
    pgo_dir = os.path.join(OUT, "pgo")
    pgd = os.path.join(pgo_dir, "boot.pgd")
    objs = f'"{os.path.join(OBJ, "*.obj")}" "{os.path.join(OBJ, "boot", "*.obj")}"'
    libs = " ".join(LIBS["boot"])
    bat = os.path.join(pgo_dir, "link.bat")

    def link(mode, exe):
        with open(bat, "w") as f:
            f.write(f'@call "{vcvars()}" >nul 2>nul\n')
            f.write(f'link /nologo /DEBUG /PDBALTPATH:%%_PDB%% /MANIFEST:EMBED /LTCG:{mode} /PGD:"{pgd}" /OUT:"{exe}" {objs} {libs} '
                    "|| exit /b 1\n")
        subprocess.check_call(["cmd", "/c", bat])

    os.makedirs(pgo_dir, exist_ok=True)
    if train or not glob.glob(os.path.join(pgo_dir, "boot!*.pgc")):
        if not os.path.exists(DOL):
            print("pgo: no game in orig/R8AE01 to train with; linked without a profile")
            return
        for f in glob.glob(os.path.join(pgo_dir, "boot!*.pgc")):
            os.remove(f)
        exe = os.path.join(pgo_dir, "boot.exe")
        link("PGINSTRUMENT", exe)
        # The instrumented program needs the profiling runtime beside it.
        with open(bat, "w") as f:
            f.write(f'@call "{vcvars()}" >nul 2>nul\nwhere pgort140.dll\n')
        runtime = subprocess.check_output(["cmd", "/c", bat], text=True).split("\n")[0].strip()
        shutil.copy2(runtime, pgo_dir)
        shutil.copytree(os.path.join(ROOT, "recomp", "assets", "prompts"), os.path.join(pgo_dir, "prompts"),
                        dirs_exist_ok=True)
        nand = os.path.join(pgo_dir, "nand")
        shutil.rmtree(nand, ignore_errors=True)
        shutil.copytree(os.path.join(ROOT, "orig", "R8AE01", "nand"), nand)
        env = dict(os.environ, RECOMP_NAND=nand, RECOMP_SKIP_MOVIES="1", RECOMP_GX_HIDDEN="1", RECOMP_AUDIO="0",
                   RECOMP_SETTINGS=os.path.join(pgo_dir, "settings.ini"), RECOMP_PAD_SCRIPT=pgo_script())
        print("pgo: training, about 5 minutes")
        subprocess.call([exe, DOL, "290"], env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        shutil.rmtree(nand, ignore_errors=True)
        # Only the profile is kept: the instrumented program is ~70 MB with its symbols.
        for f in ("boot.exe", "boot.pdb", "boot.ilk"):
            if os.path.exists(os.path.join(pgo_dir, f)):
                os.remove(os.path.join(pgo_dir, f))
    link("PGOPTIMIZE", os.path.join(OUT, "boot.exe"))


def build_cc(common, targets, opt):
    inc = ["-I", os.path.join(ROOT, "recomp", "runtime"), "-I", GEN, "-I", os.path.join(ROOT, "src")]
    defs = [f"-D{d}" for d in DEFINES]
    objdir = OBJ

    def compile_(srcs, odir):
        os.makedirs(odir, exist_ok=True)
        objs = []
        for s in srcs:
            o = os.path.join(odir, os.path.basename(s) + ".o")
            if stale(s, o):
                cmd = (["cc", "-std=c99"] if s.endswith(".c") else ["c++", "-std=c++17"])
                subprocess.check_call(cmd + [opt, "-g", "-w", "-c", s, "-o", o] + inc + defs)
            objs.append(o)
        return objs

    common_objs = compile_(common, objdir)
    for name, srcs in targets.items():
        objs = compile_(srcs, os.path.join(objdir, name))
        subprocess.check_call(["c++", "-o", os.path.join(OUT, name)] + common_objs + objs + ["-lm", "-lpthread"])


